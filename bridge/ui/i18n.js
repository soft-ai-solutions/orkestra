  /** `tr`, `TR`, `tr-TR`, `tr_TR.UTF-8`, `Turkish` -> "tr"; `en-GB` -> "en"; anything else -> null. */
  function normalize(code) {
    if (typeof code !== "string") return null;
    const raw = code.trim().toLowerCase();
    if (!raw) return null;
    const names = { english: "en", turkish: "tr", turkce: "tr", "türkçe": "tr", ingilizce: "en" };
    if (Object.prototype.hasOwnProperty.call(names, raw)) return names[raw];
    const head = raw.split(/[._@:-]/, 1)[0];
    return SUPPORTED.includes(head) ? head : null;
  }

  /**
   * The language of the page. Inputs are all optional; the first usable one wins in this order: `search` (the query
   * string, ?lang=), `stored` (the button's choice), `server` (/health), `browser` (navigator.languages), English.
   */
  function pickLanguage({ search, stored, server, browser } = {}) {
    let fromQuery = null;
    try {
      fromQuery = normalize(new URLSearchParams(search || "").get("lang"));
    } catch (error) {
      fromQuery = null;
    }
    const candidates = [fromQuery, normalize(stored), normalize(server)];
    for (const language of Array.isArray(browser) ? browser : [browser]) candidates.push(normalize(language));
    return candidates.find(Boolean) || DEFAULT;
  }

  /** Message `key` in `lang` (English, then the key itself, when missing); `{name}` filled from `params`. */
  function translate(lang, key, params) {
    const table = MESSAGES[lang] || MESSAGES[DEFAULT];
    const values = params || {};
    let template = table[key];
    if (values.n === 1 && table[`${key}_one`] !== undefined) template = table[`${key}_one`];
    if (template === undefined) template = MESSAGES[DEFAULT][key];
    if (template === undefined) return key;
    return template.replace(/\{(\w+)\}/g, (whole, name) => (values[name] === undefined ? whole : String(values[name])));
  }

  return { SUPPORTED, DEFAULT, LANGUAGE_NAMES, LOCALES, MESSAGES, normalize, pickLanguage, translate };
